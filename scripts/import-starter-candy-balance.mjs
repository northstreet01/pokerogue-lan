// Import executable upstream balance functions, erasing types only.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import ts from 'typescript';

const reference = process.argv[2];
if (!reference) throw Error('Usage: node scripts/import-starter-candy-balance.mjs <upstream-checkout>');
const sourcePath = 'src/data/balance/starters.ts';
const source = fs.readFileSync(path.join(reference, sourcePath), 'utf8');
const ast = ts.createSourceFile(sourcePath, source, ts.ScriptTarget.Latest, true);
const names = new Set(['CLASSIC_CANDY_FRIENDSHIP_MULTIPLIER', 'allStarterCandyCosts',
  'getStarterValueFriendshipCap', 'getPassiveCandyCount', 'getValueReductionCandyCounts', 'getSameSpeciesEggCandyCounts']);
const statements = ast.statements.filter(node => ts.isFunctionDeclaration(node) ? names.has(node.name.text)
  : ts.isVariableStatement(node) && node.declarationList.declarations.some(d => names.has(d.name.getText(ast))));
if (statements.length !== names.size) throw Error('UPSTREAM_CANDY_BALANCE_CHANGED');
const code = ts.transpileModule(statements.map(node => node.getFullText(ast)).join('\n'), {
  compilerOptions: {module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022, removeComments: false}
}).outputText;
fs.mkdirSync('src/data/balance', {recursive: true});
fs.writeFileSync('src/data/balance/starter-candy.mjs',
  `// Imported from pagefaultgames/pokerogue ${sourcePath}; AGPL-3.0.\n// Source SHA256: ${crypto.createHash('sha256').update(source).digest('hex')}\n// Generated by scripts/import-starter-candy-balance.mjs; only TypeScript types are erased.\n${code}`);
